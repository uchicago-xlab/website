#!/usr/bin/env python3
"""Builds the Google Apps Script version of the team tracker.

Reads tracker/index.html and inlines tracker.css and the JS files into
tracker/apps-script/Index.html (Apps Script serves a single HTML file), and
copies the shared core and seed files to Core.gs and Seed.gs.

Run from the repository root:  python3 scripts/build-tracker.py
Then push tracker/apps-script/ with clasp, or paste the files into the editor.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "tracker"
OUT = SRC / "apps-script"
BANNER = "Generated by scripts/build-tracker.py from tracker/{name}. Edit that file, not this one."


def read(name):
    return (SRC / name).read_text(encoding="utf-8")


def main():
    html = read("index.html")

    css = read("tracker.css")
    html, n_style = re.subn(
        r"<!--BUILD:STYLE-->.*?<!--/BUILD:STYLE-->",
        lambda _m: "<style>\n" + css + "\n</style>",
        html,
        flags=re.S,
    )

    block = re.search(r"<!--BUILD:SCRIPTS-->(.*?)<!--/BUILD:SCRIPTS-->", html, flags=re.S)
    if not n_style or not block:
        sys.exit("index.html is missing the BUILD markers")
    names = re.findall(r'<script src="([^"]+)"></script>', block.group(1))
    parts = []
    for name in names:
        js = read(name)
        if "</script" in js.lower():
            sys.exit(f"{name} contains a literal </script> and cannot be inlined")
        parts.append(f"<script>\n/* {name} */\n{js}\n</script>")
    html = html[: block.start()] + "\n".join(parts) + html[block.end():]
    html = "<!-- " + BANNER.format(name="index.html and its CSS/JS") + " -->\n" + html

    OUT.mkdir(exist_ok=True)
    (OUT / "Index.html").write_text(html, encoding="utf-8")
    for src, dest in (("core.js", "Core.gs"), ("seed.js", "Seed.gs")):
        (OUT / dest).write_text("/* " + BANNER.format(name=src) + " */\n" + read(src), encoding="utf-8")
    size = (OUT / "Index.html").stat().st_size // 1024
    print(f"Built {OUT.relative_to(ROOT)}/Index.html ({size} KB), Core.gs, Seed.gs")


if __name__ == "__main__":
    main()
